#!/usr/bin/env bash
# Environment check / deployment helper for the Quectel Pi M2 video player demo.
#
# M4 deployment contract:
#   1. validate the runtime environment (--check, board-only features optional)
#   2. register the launcher on PATH            (~/.local/bin/video-player-demo)
#   3. install a desktop entry                  (~/.local/share/applications)
#   4. install the app icon and, on GNOME, the bundled Desktop Icons NG
#      extension so icons actually appear on the desktop (user-level only)
#   5. print "Deployment complete." with the exact paths that were written
#
# The script never runs apt and never installs system packages as root: board
# packages are documented in docs/BOARD.md and README.md.  Deployment is per-user
# (XDG directories) so it works without sudo on the board.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="$SCRIPT_DIR"
PYTHON_BIN="${PYTHON_BIN:-python3}"
VENV_DIR=""
REQUIRE_BOARD=0
DRY_RUN=0
INSTALL_DESKTOP=1
DESKTOP_DIR_OVERRIDE=""
BIN_DIR_OVERRIDE=""
ICON_NAME="video-player-demo"
ICON_THEME_DIR="$HOME/.local/share/icons/hicolor"
ICON_SVG="$ICON_THEME_DIR/scalable/apps/$ICON_NAME.svg"
DING_SRC="$SCRIPT_DIR/assets/desktop-icons"
DING_UUID="ding@rastersoft.com"

usage() {
  cat <<'EOF'
Usage: ./install.sh [options]

Options:
  --python PATH         Python interpreter to use (default: python3)
  --venv DIR            Create/refresh a virtual environment in DIR (optional)
  --require-board       Fail when RK3576 board features are missing
  --no-desktop          Do not install the launcher and desktop entry
  --desktop-dir DIR     Applications directory (default: XDG data dir)
  --bin-dir DIR         Launcher directory (default: ~/.local/bin)
  --dry-run             Print the commands that would run, then exit
  -h, --help            Show this help and exit

On the board, --require-board is recommended: it turns the board-only checks
(mppvideodec, mpph264enc, waylandsink, gtk4paintablesink, librknnrt, librga)
into hard failures.  A missing models/*.rknn file only warns, because face
detection and automatic beauty are optional features.

Deployment is per-user: the script writes a launcher and a desktop entry into
XDG directories, then prints "Deployment complete." with the paths.
EOF
}

log() { printf '[install] %s\n' "$*"; }
fail() { printf '[install] error: %s\n' "$*" >&2; exit 1; }

run() {
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '[dry-run] %s\n' "$*"
    return 0
  fi
  "$@"
}

# Write the per-user launcher and desktop entry (M4 deployment contract).
install_launcher() {
  if [ "$INSTALL_DESKTOP" -eq 0 ]; then
    log "skipping launcher and desktop entry (--no-desktop)"
    return 0
  fi

  BIN_DIR="${BIN_DIR_OVERRIDE:-$HOME/.local/bin}"
  DESKTOP_DIR="${DESKTOP_DIR_OVERRIDE:-${XDG_DATA_HOME:-$HOME/.local/share}/applications}"
  case "$BIN_DIR" in /*) ;; *) BIN_DIR="$PWD/$BIN_DIR" ;; esac
  case "$DESKTOP_DIR" in /*) ;; *) DESKTOP_DIR="$PWD/$DESKTOP_DIR" ;; esac
  LAUNCHER="$BIN_DIR/video-player-demo"
  DESKTOP_FILE="$DESKTOP_DIR/video-player-demo.desktop"

  if [ "$DRY_RUN" -eq 1 ]; then
    printf '[dry-run] mkdir -p %s %s\n' "$BIN_DIR" "$DESKTOP_DIR"
    printf '[dry-run] write launcher %s\n' "$LAUNCHER"
    printf '[dry-run] write desktop entry %s\n' "$DESKTOP_FILE"
    LAUNCHER_PATH="$LAUNCHER"
    DESKTOP_PATH="$DESKTOP_FILE"
    return 0
  fi

  mkdir -p "$BIN_DIR" "$DESKTOP_DIR"

  cat > "$LAUNCHER" <<LAUNCHER_EOF
#!/usr/bin/env bash
# Generated by install.sh -- launches the Quectel Pi M2 video player demo.
set -euo pipefail
export PYTHONPATH="$APP_DIR/src\${PYTHONPATH:+:\$PYTHONPATH}"
exec "$PYTHON_PATH" -m video_player "\$@"
LAUNCHER_EOF
  chmod +x "$LAUNCHER"
  log "launcher installed: $LAUNCHER"

  cat > "$DESKTOP_FILE" <<DESKTOP_EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=Video Player
Name[zh_CN]=视频播放器
Comment=Hardware-decoded video player with NPU face detection and GPU beauty
Comment[zh_CN]=硬件解码本地视频播放器，带 NPU 人脸检测与 GPU 美颜
Exec=$LAUNCHER %f
Icon=$ICON_SVG
Terminal=false
Categories=AudioVideo;Video;Player;
Keywords=video;player;beauty;rk3576;
StartupWMClass=io.quectel.pi.VideoPlayer
DESKTOP_EOF
  log "desktop entry installed: $DESKTOP_FILE"
  LAUNCHER_PATH="$LAUNCHER"
  DESKTOP_PATH="$DESKTOP_FILE"
}

# Install a dedicated app icon (SVG + rasterized PNGs), a desktop shortcut and
# a GNOME Dash favourite.  Every step is best-effort: playback never depends on
# the icon, and a missing desktop-icons extension simply leaves no desktop icon.
install_icon() {
  if [ "$INSTALL_DESKTOP" -eq 0 ]; then
    log "skipping icon (--no-desktop)"
    return 0
  fi
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '[dry-run] write icon %s\n' "$ICON_SVG"
    return 0
  fi

  mkdir -p "$(dirname "$ICON_SVG")"
  cat > "$ICON_SVG" <<'ICON_EOF'
<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#20345c"/>
      <stop offset="1" stop-color="#0b1220"/>
    </linearGradient>
    <linearGradient id="ring" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#5ee7f0"/>
      <stop offset="1" stop-color="#4b7bff"/>
    </linearGradient>
  </defs>
  <rect x="8" y="8" width="240" height="240" rx="54" fill="url(#bg)"/>
  <rect x="14" y="14" width="228" height="228" rx="48" fill="none" stroke="#ffffff" stroke-opacity="0.10" stroke-width="3"/>
  <circle cx="128" cy="128" r="74" fill="none" stroke="url(#ring)" stroke-width="10"/>
  <circle cx="128" cy="128" r="65" fill="none" stroke="#ffffff" stroke-opacity="0.16" stroke-width="2"/>
  <path d="M110 90 L110 166 L174 128 Z" fill="#ffffff"/>
</svg>
ICON_EOF

  # Rasterize for launchers that only accept PNG (best effort).
  "$PYTHON_BIN" - "$ICON_SVG" "$ICON_THEME_DIR" <<'PY_EOF' 2>/dev/null || log "warning: PNG rasterization unavailable; SVG icon is still valid"
import os
import sys
import gi
gi.require_version("GdkPixbuf", "2.0")
from gi.repository import GdkPixbuf
svg, root = sys.argv[1], sys.argv[2]
for size in (48, 64, 128, 256):
    out = os.path.join(root, "%dx%d" % (size, size), "apps")
    os.makedirs(out, exist_ok=True)
    pb = GdkPixbuf.Pixbuf.new_from_file_at_scale(svg, size, size, True)
    pb.savev(os.path.join(out, "video-player-demo.png"), "png", [], [])
print("[icon] rasterized 48/64/128/256 PNG")
PY_EOF

  # Desktop shortcut (shown when a desktop-icons extension is installed).
  if [ -d "$HOME/Desktop" ]; then
    cp "$DESKTOP_FILE" "$HOME/Desktop/$ICON_NAME.desktop"
    chmod +x "$HOME/Desktop/$ICON_NAME.desktop"
    gio set "$HOME/Desktop/$ICON_NAME.desktop" metadata::trusted true 2>/dev/null || true
    log "desktop shortcut: $HOME/Desktop/$ICON_NAME.desktop"
  fi

  # Pin to the GNOME Dash so the icon is visible in the Activities overview.
  "$PYTHON_BIN" - <<'PY_EOF' 2>/dev/null || log "warning: could not pin to GNOME Dash"
import gi
gi.require_version("Gio", "2.0")
from gi.repository import Gio
s = Gio.Settings.new("org.gnome.shell")
fav = list(s.get_strv("favorite-apps"))
if "video-player-demo.desktop" not in fav:
    fav.append("video-player-demo.desktop")
    s.set_strv("favorite-apps", fav)
print("[icon] pinned to GNOME Dash")
PY_EOF

  update-desktop-database "$(dirname "$DESKTOP_FILE")" 2>/dev/null || true
  gtk-update-icon-cache -f -t "$ICON_THEME_DIR" 2>/dev/null || true
  log "icon installed: $ICON_SVG"
}

# Install the bundled Desktop Icons NG (DING) extension so GNOME paints icons
# on the desktop.  User-level only: no root, no apt, no network.  Best-effort --
# playback and the launcher never depend on it.  GNOME Shell scans extension
# directories only at startup, so on a running Wayland session the icons appear
# after one log out / log in.
install_desktop_icons() {
  if [ "$INSTALL_DESKTOP" -eq 0 ]; then
    log "skipping desktop-icons extension (--no-desktop)"
    return 0
  fi
  if [ ! -d "$DING_SRC/$DING_UUID" ]; then
    log "warning: bundled desktop-icons extension missing at $DING_SRC; skipping"
    return 0
  fi
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '[dry-run] install desktop-icons %s -> %s/.local/share/gnome-shell/extensions/%s\n' \
      "$DING_SRC/$DING_UUID" "$HOME" "$DING_UUID"
    return 0
  fi
  if ! command -v gnome-shell >/dev/null 2>&1; then
    log "gnome-shell not found; skipping desktop-icons extension"
    return 0
  fi
  case "${XDG_CURRENT_DESKTOP:-}" in
    "" | *[Gg][Nn][Oo][Mm][Ee]*) ;;
    *)
      log "desktop is not GNOME (XDG_CURRENT_DESKTOP=$XDG_CURRENT_DESKTOP); skipping desktop-icons extension"
      return 0
      ;;
  esac

  EXT_DIR="$HOME/.local/share/gnome-shell/extensions/$DING_UUID"
  SCHEMA_DIR="$HOME/.local/share/glib-2.0/schemas"
  mkdir -p "$EXT_DIR" "$SCHEMA_DIR"
  cp -a "$DING_SRC/$DING_UUID/." "$EXT_DIR/"
  if [ -d "$DING_SRC/schemas" ]; then
    cp -a "$DING_SRC/schemas/." "$SCHEMA_DIR/"
    glib-compile-schemas "$SCHEMA_DIR" 2>/dev/null || \
      log "warning: glib-compile-schemas failed; the extension may not load"
  fi

  # Needed when invoked from a non-interactive SSH session (no session bus yet).
  if [ -z "${DBUS_SESSION_BUS_ADDRESS:-}" ] && [ -S "/run/user/$(id -u)/bus" ]; then
    export XDG_RUNTIME_DIR="/run/user/$(id -u)"
    export DBUS_SESSION_BUS_ADDRESS="unix:path=/run/user/$(id -u)/bus"
  fi

  # Append to enabled-extensions without clobbering the user's other extensions.
  "$PYTHON_BIN" - "$DING_UUID" <<'DING_EOF' 2>/dev/null || \
    log "warning: could not enable desktop-icons via GSettings (enable it in the Extensions app)"
import sys

import gi

gi.require_version("Gio", "2.0")
from gi.repository import Gio

uuid = sys.argv[1]
settings = Gio.Settings.new("org.gnome.shell")
enabled = list(settings.get_strv("enabled-extensions"))
if uuid not in enabled:
    enabled.append(uuid)
    settings.set_strv("enabled-extensions", enabled)
print("[ding] enabled", uuid)
DING_EOF

  log "desktop-icons extension installed: $EXT_DIR"
  log "note: GNOME Shell loads extensions at startup; log out and back in once (or reboot) on Wayland"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --python)
      [ $# -ge 2 ] || fail "--python needs a value"
      PYTHON_BIN="$2"
      shift 2
      ;;
    --python=*)
      PYTHON_BIN="${1#*=}"
      shift
      ;;
    --venv)
      [ $# -ge 2 ] || fail "--venv needs a value"
      VENV_DIR="$2"
      shift 2
      ;;
    --venv=*)
      VENV_DIR="${1#*=}"
      shift
      ;;
    --require-board)
      REQUIRE_BOARD=1
      shift
      ;;
    --no-desktop)
      INSTALL_DESKTOP=0
      shift
      ;;
    --desktop-dir)
      [ $# -ge 2 ] || fail "--desktop-dir needs a value"
      DESKTOP_DIR_OVERRIDE="$2"
      shift 2
      ;;
    --desktop-dir=*)
      DESKTOP_DIR_OVERRIDE="${1#*=}"
      shift
      ;;
    --bin-dir)
      [ $# -ge 2 ] || fail "--bin-dir needs a value"
      BIN_DIR_OVERRIDE="$2"
      shift 2
      ;;
    --bin-dir=*)
      BIN_DIR_OVERRIDE="${1#*=}"
      shift
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      fail "unknown option: $1 (try --help)"
      ;;
  esac
done

command -v "$PYTHON_BIN" >/dev/null 2>&1 || fail "Python interpreter not found: $PYTHON_BIN"
PY_VERSION="$("$PYTHON_BIN" -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
PY_VERSION_CODE="$("$PYTHON_BIN" -c 'import sys; print(sys.version_info[0] * 100 + sys.version_info[1])')"
[ "$PY_VERSION_CODE" -ge 310 ] || fail "Python >= 3.10 is required, found $PY_VERSION"

log "project directory: $APP_DIR"
log "python: $PYTHON_BIN ($PY_VERSION)"

command -v gst-inspect-1.0 >/dev/null 2>&1 || \
  log "warning: gst-inspect-1.0 not found; install GStreamer tools (see README)"
if [ -z "${WAYLAND_DISPLAY:-}" ] && [ -z "${DISPLAY:-}" ]; then
  log "warning: no graphical session detected; the environment check still works headless"
fi

PYTHON_RUN="$PYTHON_BIN"
if [ -n "$VENV_DIR" ]; then
  if [ ! -d "$VENV_DIR" ]; then
    log "creating virtual environment: $VENV_DIR (with system site packages)"
    run "$PYTHON_BIN" -m venv --system-site-packages "$VENV_DIR"
  else
    log "reusing virtual environment: $VENV_DIR"
  fi
  PYTHON_RUN="$VENV_DIR/bin/python"
  if [ "$DRY_RUN" -eq 0 ]; then
    PTH_DIR="$("$PYTHON_RUN" -c 'import site; print(site.getsitepackages()[0])')" || \
      fail "cannot locate site-packages inside $VENV_DIR"
    printf '%s\n' "$APP_DIR/src" > "$PTH_DIR/_video_player_src.pth"
    log "registered src path in $PTH_DIR/_video_player_src.pth"
    if [ -f "$APP_DIR/requirements.txt" ]; then
      "$PYTHON_RUN" -m pip install --disable-pip-version-check -q -r "$APP_DIR/requirements.txt" || \
        log "warning: pip install failed; installing NumPy is optional on the board (apt python3-numpy)"
    fi
  fi
fi

if [ "$DRY_RUN" -eq 1 ]; then
  PYTHON_PATH="$PYTHON_BIN"
else
  PYTHON_PATH="$(command -v "$PYTHON_RUN")" || fail "cannot resolve Python interpreter: $PYTHON_RUN"
fi

CHECK_CMD=(-m video_player --check)
if [ "$REQUIRE_BOARD" -eq 1 ]; then
  CHECK_CMD+=(--require-board)
fi

log "running environment check"
if [ "$DRY_RUN" -eq 1 ]; then
  printf '[dry-run] PYTHONPATH=%s %s %s\n' "$APP_DIR/src" "$PYTHON_RUN" "${CHECK_CMD[*]}"
  exit 0
fi

set +e
PYTHONPATH="$APP_DIR/src${PYTHONPATH:+:$PYTHONPATH}" \
  "$PYTHON_RUN" "${CHECK_CMD[@]}"
CHECK_STATUS=$?
set -e

if [ "$CHECK_STATUS" -ne 0 ]; then
  printf '\nEnvironment check failed (exit %d).\n' "$CHECK_STATUS" >&2
  printf 'Required packages and expected board features are listed in docs/BOARD.md.\n' >&2
  exit "$CHECK_STATUS"
fi

install_launcher
install_icon
install_desktop_icons

cat <<EOF

Deployment complete.

  project:        $APP_DIR
  python:         $PYTHON_PATH ($PY_VERSION)
  launcher:       ${LAUNCHER_PATH:-skipped (--no-desktop)}
  desktop entry:  ${DESKTOP_PATH:-skipped (--no-desktop)}

Launch the player from the desktop menu ("Video Player" / "视频播放器") or run:
  ${LAUNCHER_PATH:-python3 scripts/launch_player.py} --demo /path/to/video.mp4

Notes:
  - system packages (GStreamer, GTK4, librknnrt, librga) ship with the Debian 13
    board image; docs/BOARD.md lists the exact packages and verification commands
  - RKNN models are not committed: generate models/yunet_rk3576.rknn with
    scripts/convert_yunet.py before enabling face detection
  - re-run the environment check any time:  python3 -m video_player --check
EOF
