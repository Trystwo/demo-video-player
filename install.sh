#!/usr/bin/env bash
# Environment check / deployment helper for the Quectel Pi M2 video player demo.
#
# M4 deployment contract:
#   1. validate the runtime environment (--check, board-only features optional)
#   2. register the launcher on PATH            (~/.local/bin/video-player-demo)
#   3. install a desktop entry                  (~/.local/share/applications)
#   4. print "Deployment complete." with the exact paths that were written
#
# The script never runs apt and never installs system packages as root: board
# packages are documented in docs/BOARD.md and README.md.  Deployment is per-user
# (XDG directories) so it works without sudo on the board.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="$SCRIPT_DIR"
PYTHON_BIN="${PYTHON_BIN:-python3}"
VENV_DIR=""
REQUIRE_BOARD=0
DRY_RUN=0
INSTALL_DESKTOP=1
DESKTOP_DIR_OVERRIDE=""
BIN_DIR_OVERRIDE=""

usage() {
  cat <<'EOF'
Usage: ./install.sh [options]

Options:
  --python PATH         Python interpreter to use (default: python3)
  --venv DIR            Create/refresh a virtual environment in DIR (optional)
  --require-board       Fail when RK3576 board features are missing
  --no-desktop          Do not install the launcher and desktop entry
  --desktop-dir DIR     Applications directory (default: XDG data dir)
  --bin-dir DIR         Launcher directory (default: ~/.local/bin)
  --dry-run             Print the commands that would run, then exit
  -h, --help            Show this help and exit

On the board, --require-board is recommended: it turns the board-only checks
(mppvideodec, mpph264enc, waylandsink, gtk4paintablesink, librknnrt, librga)
into hard failures.  A missing models/*.rknn file only warns, because face
detection and automatic beauty are optional features.

Deployment is per-user: the script writes a launcher and a desktop entry into
XDG directories, then prints "Deployment complete." with the paths.
EOF
}

log() { printf '[install] %s\n' "$*"; }
fail() { printf '[install] error: %s\n' "$*" >&2; exit 1; }

run() {
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '[dry-run] %s\n' "$*"
    return 0
  fi
  "$@"
}

# Write the per-user launcher and desktop entry (M4 deployment contract).
install_launcher() {
  if [ "$INSTALL_DESKTOP" -eq 0 ]; then
    log "skipping launcher and desktop entry (--no-desktop)"
    return 0
  fi

  BIN_DIR="${BIN_DIR_OVERRIDE:-$HOME/.local/bin}"
  DESKTOP_DIR="${DESKTOP_DIR_OVERRIDE:-${XDG_DATA_HOME:-$HOME/.local/share}/applications}"
  case "$BIN_DIR" in /*) ;; *) BIN_DIR="$PWD/$BIN_DIR" ;; esac
  case "$DESKTOP_DIR" in /*) ;; *) DESKTOP_DIR="$PWD/$DESKTOP_DIR" ;; esac
  LAUNCHER="$BIN_DIR/video-player-demo"
  DESKTOP_FILE="$DESKTOP_DIR/video-player-demo.desktop"

  if [ "$DRY_RUN" -eq 1 ]; then
    printf '[dry-run] mkdir -p %s %s\n' "$BIN_DIR" "$DESKTOP_DIR"
    printf '[dry-run] write launcher %s\n' "$LAUNCHER"
    printf '[dry-run] write desktop entry %s\n' "$DESKTOP_FILE"
    LAUNCHER_PATH="$LAUNCHER"
    DESKTOP_PATH="$DESKTOP_FILE"
    return 0
  fi

  mkdir -p "$BIN_DIR" "$DESKTOP_DIR"

  cat > "$LAUNCHER" <<LAUNCHER_EOF
#!/usr/bin/env bash
# Generated by install.sh -- launches the Quectel Pi M2 video player demo.
set -euo pipefail
export PYTHONPATH="$APP_DIR/src\${PYTHONPATH:+:\$PYTHONPATH}"
exec "$PYTHON_PATH" -m video_player "\$@"
LAUNCHER_EOF
  chmod +x "$LAUNCHER"
  log "launcher installed: $LAUNCHER"

  cat > "$DESKTOP_FILE" <<DESKTOP_EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=Video Player
Name[zh_CN]=视频播放器
Comment=Hardware-decoded video player with NPU face detection and GPU beauty
Comment[zh_CN]=硬件解码本地视频播放器，带 NPU 人脸检测与 GPU 美颜
Exec=$LAUNCHER %f
Icon=media-playback-start
Terminal=false
Categories=AudioVideo;Video;Player;
Keywords=video;player;beauty;rk3576;
StartupWMClass=io.quectel.pi.VideoPlayer
DESKTOP_EOF
  log "desktop entry installed: $DESKTOP_FILE"
  LAUNCHER_PATH="$LAUNCHER"
  DESKTOP_PATH="$DESKTOP_FILE"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --python)
      [ $# -ge 2 ] || fail "--python needs a value"
      PYTHON_BIN="$2"
      shift 2
      ;;
    --python=*)
      PYTHON_BIN="${1#*=}"
      shift
      ;;
    --venv)
      [ $# -ge 2 ] || fail "--venv needs a value"
      VENV_DIR="$2"
      shift 2
      ;;
    --venv=*)
      VENV_DIR="${1#*=}"
      shift
      ;;
    --require-board)
      REQUIRE_BOARD=1
      shift
      ;;
    --no-desktop)
      INSTALL_DESKTOP=0
      shift
      ;;
    --desktop-dir)
      [ $# -ge 2 ] || fail "--desktop-dir needs a value"
      DESKTOP_DIR_OVERRIDE="$2"
      shift 2
      ;;
    --desktop-dir=*)
      DESKTOP_DIR_OVERRIDE="${1#*=}"
      shift
      ;;
    --bin-dir)
      [ $# -ge 2 ] || fail "--bin-dir needs a value"
      BIN_DIR_OVERRIDE="$2"
      shift 2
      ;;
    --bin-dir=*)
      BIN_DIR_OVERRIDE="${1#*=}"
      shift
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      fail "unknown option: $1 (try --help)"
      ;;
  esac
done

command -v "$PYTHON_BIN" >/dev/null 2>&1 || fail "Python interpreter not found: $PYTHON_BIN"
PY_VERSION="$("$PYTHON_BIN" -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
PY_VERSION_CODE="$("$PYTHON_BIN" -c 'import sys; print(sys.version_info[0] * 100 + sys.version_info[1])')"
[ "$PY_VERSION_CODE" -ge 310 ] || fail "Python >= 3.10 is required, found $PY_VERSION"

log "project directory: $APP_DIR"
log "python: $PYTHON_BIN ($PY_VERSION)"

command -v gst-inspect-1.0 >/dev/null 2>&1 || \
  log "warning: gst-inspect-1.0 not found; install GStreamer tools (see README)"
if [ -z "${WAYLAND_DISPLAY:-}" ] && [ -z "${DISPLAY:-}" ]; then
  log "warning: no graphical session detected; the environment check still works headless"
fi

PYTHON_RUN="$PYTHON_BIN"
if [ -n "$VENV_DIR" ]; then
  if [ ! -d "$VENV_DIR" ]; then
    log "creating virtual environment: $VENV_DIR (with system site packages)"
    run "$PYTHON_BIN" -m venv --system-site-packages "$VENV_DIR"
  else
    log "reusing virtual environment: $VENV_DIR"
  fi
  PYTHON_RUN="$VENV_DIR/bin/python"
  if [ "$DRY_RUN" -eq 0 ]; then
    PTH_DIR="$("$PYTHON_RUN" -c 'import site; print(site.getsitepackages()[0])')" || \
      fail "cannot locate site-packages inside $VENV_DIR"
    printf '%s\n' "$APP_DIR/src" > "$PTH_DIR/_video_player_src.pth"
    log "registered src path in $PTH_DIR/_video_player_src.pth"
    if [ -f "$APP_DIR/requirements.txt" ]; then
      "$PYTHON_RUN" -m pip install --disable-pip-version-check -q -r "$APP_DIR/requirements.txt" || \
        log "warning: pip install failed; installing NumPy is optional on the board (apt python3-numpy)"
    fi
  fi
fi

if [ "$DRY_RUN" -eq 1 ]; then
  PYTHON_PATH="$PYTHON_BIN"
else
  PYTHON_PATH="$(command -v "$PYTHON_RUN")" || fail "cannot resolve Python interpreter: $PYTHON_RUN"
fi

CHECK_CMD=(-m video_player --check)
if [ "$REQUIRE_BOARD" -eq 1 ]; then
  CHECK_CMD+=(--require-board)
fi

log "running environment check"
if [ "$DRY_RUN" -eq 1 ]; then
  printf '[dry-run] PYTHONPATH=%s %s %s\n' "$APP_DIR/src" "$PYTHON_RUN" "${CHECK_CMD[*]}"
  exit 0
fi

set +e
PYTHONPATH="$APP_DIR/src${PYTHONPATH:+:$PYTHONPATH}" \
  "$PYTHON_RUN" "${CHECK_CMD[@]}"
CHECK_STATUS=$?
set -e

if [ "$CHECK_STATUS" -ne 0 ]; then
  printf '\nEnvironment check failed (exit %d).\n' "$CHECK_STATUS" >&2
  printf 'Required packages and expected board features are listed in docs/BOARD.md.\n' >&2
  exit "$CHECK_STATUS"
fi

install_launcher

cat <<EOF

Deployment complete.

  project:        $APP_DIR
  python:         $PYTHON_PATH ($PY_VERSION)
  launcher:       ${LAUNCHER_PATH:-skipped (--no-desktop)}
  desktop entry:  ${DESKTOP_PATH:-skipped (--no-desktop)}

Launch the player from the desktop menu ("Video Player" / "视频播放器") or run:
  ${LAUNCHER_PATH:-python3 scripts/launch_player.py} --demo /path/to/video.mp4

Notes:
  - system packages (GStreamer, GTK4, librknnrt, librga) ship with the Debian 13
    board image; docs/BOARD.md lists the exact packages and verification commands
  - RKNN models are not committed: generate models/yunet_rk3576.rknn with
    scripts/convert_yunet.py before enabling face detection
  - re-run the environment check any time:  python3 -m video_player --check
EOF
